L = []


def lesson(bench, q, title, why, example, turn, practice, watch):
    L.append({'bench': bench, 'q': q, 'id': f"{bench[2:]}·{q}", 'title': title, 'why': why,
              'example': example, 'turn': turn, 'practice': practice, 'watch': watch})


def P(prompt, answer, change='', steps=None, fig=None, check=None):
    return {'prompt': prompt, 'answer': answer, 'change': change, 'steps': steps or [], 'fig': fig, 'check': check}


